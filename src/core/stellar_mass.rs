use dicebag::DiceExt;

/// Generates a random[^note] approximate stellar mass.
/// 
/// [^note]: GURPS 4e Space **p.101**.
pub fn gen_stellar_mass() -> f64 {
    let r = 3.d6();
    match r {
        ..=3 => match 3.d6() {
            ..=10 => 2.0,
            _ => 1.9
        },
        4 => match 3.d6() {
            ..=8 => 1.8,
            ..=11 => 1.7,
            _ => 1.6
        },
        5 => match 3.d6() {
            ..=7 => 1.5,
            ..=10 => 1.45,
            ..=12 => 1.4,
            _ => 1.35
        },
        6|7|8 => {
            let mut x = match 3.d6() {
                ..=7 => 1.3,
                8|9 => 1.25,
                10 => 1.2,
                11|12 => 1.15,
                _ => 1.1
            };
            x -= match r {
                7 => 0.25,
                8 => 0.5,
                _ => 0.0
            };
            x
        }
        9 => match 3.d6() {
            ..=8 => 0.55,
            ..=11 => 0.5,
            _ => 0.45
        },
        10 => match 3.d6() {
            ..=8 => 0.4,
            ..=11 => 0.35,
            _ => 0.3
        },
        11 => 0.25,
        12 => 0.2,
        13 => 0.15,
        _ => 0.1
    }
}
